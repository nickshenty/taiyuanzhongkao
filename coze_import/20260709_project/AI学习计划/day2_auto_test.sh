#!/bin/bash
# ============================================================
# AI学习 Day 2 —— 自动化对比测试（一键运行版）
# 自动对3个模型执行4组测试，结果保存到文件
# ============================================================

OUTPUT_DIR="$HOME/Desktop/ai_study/day2_results"
mkdir -p "$OUTPUT_DIR"

MODELS=("qwen2.5:7b" "deepseek-r1:7b" "gemma4:12b")

# 测试问题
TEST1="请帮我润色以下会议纪要：
\"今天开了个会，讨论了上半年普惠金融业务的情况。大家觉得现在贷款增长还行，但是风险管控要加把劲。下一步要把小微信贷的流程再优化一下，争取效率更高。还有就是乡村振兴方面的工作要抓紧，上级行催的紧。\""

TEST2="以下是某支行2026年上半年普惠金融贷款数据：
1月新增320万，2月新增280万，3月新增410万，4月新增350万，5月新增520万，6月新增480万。
请分析这组数据的增长趋势，找出规律，并给出下半年的业务建议。"

TEST3="请用通俗易懂的语言解释以下监管要求的核心要点，以及对银行基层行的影响：
\"商业银行应当建立健全小微企业授信尽职免责制度，明确尽职认定标准和免责条件，对小微企业授信业务相关人员在职权范围内，按照规定勤勉尽职履行职责的，应当免除相关责任。\""

TEST4="请帮我拟一份普惠金融业务通报的框架大纲，要求：
- 时间范围：2026年上半年
- 背景：贷款余额增长12%，新拓展小微企业客户85户，不良率控制在0.8%
- 需要包含：成绩总结、存在问题、下半年工作计划
- 风格：正式、简洁、有数据支撑"

TEST_NAMES=("1_公文润色" "2_数据分析" "3_政策解读" "4_写作辅助")
TESTS=("$TEST1" "$TEST2" "$TEST3" "$TEST4")

echo "🏀 AI学习Day2：自动化模型对比测试"
echo "============================================"
echo ""

for model in "${MODELS[@]}"; do
    model_clean=$(echo "$model" | tr ':' '_')
    echo "🔄 正在测试模型: $model"
    
    for i in "${!TESTS[@]}"; do
        echo "  📝 测试 $((i+1))/4: ${TEST_NAMES[$i]}"
        output_file="$OUTPUT_DIR/${model_clean}_${TEST_NAMES[$i]}.txt"
        
        # 记录开始时间
        start_time=$(date +%s)
        
        # 执行测试（非交互模式）
        ollama run "$model" "${TESTS[$i]}" > "$output_file" 2>&1
        
        # 记录结束时间和耗时
        end_time=$(date +%s)
        duration=$((end_time - start_time))
        
        # 统计字数
        char_count=$(wc -c < "$output_file" | tr -d ' ')
        
        echo "    ✅ 完成 | 耗时: ${duration}秒 | 输出: ${char_count}字节"
        echo "    📄 结果: $output_file"
        echo ""
    done
    echo ""
done

echo "============================================"
echo "✅ 全部测试完成！"
echo "📂 结果目录: $OUTPUT_DIR"
echo ""
echo "文件列表："
ls -la "$OUTPUT_DIR"
echo ""
echo "下一步：打开各文件对比不同模型的表现，填写模型-场景对照表。"
