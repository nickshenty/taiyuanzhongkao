REVIEW_INTERVALS = [1, 2, 4, 7, 15]

def get_vocab_info(day):
    if day == 1:
        return ("测试日", 0, "无", [])
    for start, end, count, level in VOCAB_PHASES:
        if start <= day <= end:
            batch = day - start + 1
            reviews = []
            for interval in REVIEW_INTERVALS:
                src_day = day - interval
                if src_day >= 2:
                    reviews.append(f"Day{src_day}")
            return (level, batch, count, reviews)
    return ("无", 0, 0, [])

