async def main():
    result_mode = sys.argv[1] if len(sys.argv) > 1 else "display_only"
    study_data_path = sys.argv[2] if len(sys.argv) > 2 else "./codeact/scripts/study_data.json"

    print(f"[参数] result_mode={result_mode}, study_data_path={study_data_path}")
    sdk = CodeActSDK()

    try:
        # 读取 study_data.json
        with open(study_data_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        print(f"[读取] 共 {len(data)} 天数据")

        # 统计更新
        updated_physics = 0
        updated_hw = 0
        updated_main = 0

        # 遍历 Day3 到 Day57
        for day_num in range(3, 58):
            day_key = str(day_num)
            if day_key not in data:
                print(f"[警告] Day{day_num} 不存在，跳过")
                continue

            day_data = data[day_key]

            # 1. 更新 daily_learning.physics
            if day_num in PHYSICS_DAYS:
                physics_content = PHYSICS_DAYS[day_num]
                if "daily_learning" not in day_data:
                    day_data["daily_learning"] = {}
                day_data["daily_learning"]["physics"] = {
                    "topic": physics_content["topic"],
                    "content": physics_content["content"] + (CONTENT_EXPANSIONS.get(day_num, "") if len(physics_content["content"]) < 200 else ""),
                    "key_points": physics_content["key_points"],
                    "formulas": physics_content.get("formulas", []),
                    "common_mistakes": physics_content["common_mistakes"],
                    "practice_guide": physics_content["practice_guide"],
                }
                updated_physics += 1

            # 2. 更新 school_hw.physics
            if day_num in PHYSICS_HW:
                if "school_hw" not in day_data:
                    day_data["school_hw"] = {}
                day_data["school_hw"]["physics"] = PHYSICS_HW[day_num]
                updated_hw += 1

            # 3. 更新 main_subject（当 name == "物理" 时）
            if day_num in MAIN_SUBJECT_UPDATES:
                if "main_subject" in day_data and day_data["main_subject"].get("name") == "物理":
                    old_topic = day_data["main_subject"].get("topic", "")
                    day_data["main_subject"]["topic"] = MAIN_SUBJECT_UPDATES[day_num]
                    updated_main += 1
                    print(f"[更新] Day{day_num} main_subject: {old_topic[:40]}... → {MAIN_SUBJECT_UPDATES[day_num][:40]}...")

        # 写回 study_data.json
        with open(study_data_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"[完成] 更新 daily_learning.physics: {updated_physics} 天")
        print(f"[完成] 更新 school_hw.physics: {updated_hw} 天")
        print(f"[完成] 更新 main_subject: {updated_main} 天")
        print(f"[完成] 文件已保存到: {study_data_path}")

        actual_mode = result_mode if result_mode != "auto" else "display_only"

        # 生成简要摘要
        summary_lines = [
            f"物理暑假作业内容已更新到 study_data.json",
            f"更新范围：Day3-Day57（共55天）",
            f"• daily_learning.physics 更新：{updated_physics} 天",
            f"• school_hw.physics 新增：{updated_hw} 天",
            f"• main_subject（物理日）更新：{updated_main} 天",
            f"• Day1-2 保持不变",
            f"",
            f"作业分配：",
            f"  Day3-7:   作业1 抛体运动1",
            f"  Day8-12:  作业2 抛体运动2",
            f"  Day13-17: 作业3 圆周运动1",
            f"  Day18-22: 作业4 圆周运动2",
            f"  Day23-27: 作业5 天体1",
            f"  Day28-32: 作业6 天体2",
            f"  Day33-37: 作业7 机械能守恒1",
            f"  Day38-42: 作业8 机械能2",
            f"  Day43-47: 作业9 动量守恒1",
            f"  Day48-52: 作业10 动量守恒2",
            f"  Day53-57: 物理综合复习",
        ]

        await sdk.submit_result(
            result_mode=actual_mode,
            status="success",
            message="\n".join(summary_lines),
            data={
                "updated_physics_days": updated_physics,
                "updated_hw_days": updated_hw,
                "updated_main_subject_days": updated_main,
                "file_path": study_data_path,
            },
        )

    except Exception as e:
        import traceback
        traceback.print_exc()
        await sdk.submit_result(
            result_mode="notify",
            status="error",
            message=f"更新物理内容失败: {e}",
            data={"error_type": type(e).__name__},
        )


if __name__ == "__main__":
    asyncio.run(main())
